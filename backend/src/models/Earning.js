// VALIDATION MIDDLEWARE
// ============================================================

earningSchema.pre(
  "validate",
  function (next) {
    try {
      const amount =
        toNumber(
          this.amount,
          0
        );

      const platformFee =
        toNumber(
          this.platformFee,
          0
        );

      const netAmount =
        toNumber(
          this.netAmount,
          0
        );

      const availableAmount =
        toNumber(
          this.availableAmount,
          0
        );

      const withdrawnAmount =
        toNumber(
          this.withdrawnAmount,
          0
        );

      const refundedAmount =
        toNumber(
          this.refundedAmount,
          0
        );

      if (
        amount <= 0
      ) {
        return next(
          new Error(
            "Earning amount must be greater than 0"
          )
        );
      }

      /*
       * STRICT MVP RULE
       */
      if (
        platformFee !== 0
      ) {
        return next(
          new Error(
            "AI Tour MVP platform fee must be 0"
          )
        );
      }

      if (
        platformFee >
        amount
      ) {
        return next(
          new Error(
            "Platform fee cannot exceed earning amount"
          )
        );
      }

      if (
        netAmount < 0
      ) {
        return next(
          new Error(
            "Net earning amount is invalid"
          )
        );
      }

      if (
        availableAmount < 0
      ) {
        return next(
          new Error(
            "Available earning amount cannot be negative"
          )
        );
      }

      if (
        withdrawnAmount < 0
      ) {
        return next(
          new Error(
            "Withdrawn earning amount cannot be negative"
          )
        );
      }

      if (
        refundedAmount < 0
      ) {
        return next(
          new Error(
            "Refunded earning amount cannot be negative"
          )
        );
      }

      const totalAllocated =
        roundMoney(
          availableAmount +
            withdrawnAmount +
            refundedAmount
        );

      if (
        totalAllocated >
        roundMoney(
          netAmount
        ) +
          0.01
      ) {
        return next(
          new Error(
            "Earning financial allocations exceed net amount"
          )
        );
      }

      /*
       * Settlement amount cannot be negative.
       */
      if (
        toNumber(
          this.settlementAmount,
          0
        ) < 0
      ) {
        return next(
          new Error(
            "Settlement amount cannot be negative"
          )
        );
      }

      /*
       * Settlement fee cannot be negative.
       */
      if (
        toNumber(
          this.settlementFee,
          0
        ) < 0
      ) {
        return next(
          new Error(
            "Settlement fee cannot be negative"
          )
        );
      }

      /*
       * Exchange rate must be positive when used.
       */
      const exchangeRate =
        toNumber(
          this.settlementExchangeRate,
          1
        );

      if (
        exchangeRate <= 0
      ) {
        return next(
          new Error(
            "Settlement exchange rate must be greater than 0"
          )
        );
      }

      next();
    } catch (error) {
      next(error);
    }
  }
);

// ============================================================
// SAVE MIDDLEWARE
// ============================================================

earningSchema.pre(
  "save",
  function (next) {
    try {
      /*
       * MVP platform commission is always zero.
       */
      this.platformFee =
        0;

      /*
       * Normalize currency.
       */
      if (
        this.currency
      ) {
        this.currency =
          String(
            this.currency
          ).toUpperCase();
      }

      if (
        this.settlementCurrency
      ) {
        this.settlementCurrency =
          String(
            this.settlementCurrency
          ).toUpperCase();
      }

      /*
       * Normalize status.
       */
      if (
        this.status
      ) {
        this.status =
          String(
            this.status
          ).toLowerCase();
      }

      /*
       * Always maintain netAmount = amount in MVP.
       */
      this.netAmount =
        roundMoney(
          this.amount
        );

      /*
       * IMPORTANT:
       *
       * Do NOT blindly recalculate availableAmount on every
       * save.
       *
       * reserveForWithdrawal() intentionally changes:
       *
       * availableAmount
       * withdrawnAmount
       *
       * and those values must survive save().
       */
      if (
        this.isNew
      ) {
        this.withdrawnAmount =
          0;

        this.refundedAmount =
          0;

        if (
          this.status ===
          "available"
        ) {
          this.availableAmount =
            this.netAmount;
        } else {
          this.availableAmount =
            0;
        }
      }

      /*
       * Only recalculate available amount if the earning's
       * base amount itself was intentionally changed.
       */
      if (
        !this.isNew &&
        (
          this.isModified(
            "amount"
          ) ||
          this.isModified(
            "platformFee"
          )
        )
      ) {
        const withdrawn =
          toNumber(
            this.withdrawnAmount,
            0
          );

        const refunded =
          toNumber(
            this.refundedAmount,
            0
          );

        this.availableAmount =
          roundMoney(
            Math.max(
              0,
              this.netAmount -
                withdrawn -
                refunded
            )
          );
      }

      /*
       * If no available amount remains but money is still
       * allocated/withdrawn, classify as withdrawn.
       */
      if (
        this.status ===
          "available" &&
        this.availableAmount <=
          0 &&
        this.withdrawnAmount >
          0
      ) {
        this.availableAmount =
          0;

        this.status =
          "withdrawn";

        this.withdrawnAt =
          this.withdrawnAt ||
          new Date();
      }

      /*
       * If all net earning has been refunded and there is
       * no withdrawal allocation remaining, classify refunded.
       */
      if (
        this.refundedAmount >=
          this.netAmount &&
        this.withdrawnAmount <=
          0
      ) {
        this.availableAmount =
          0;

        this.status =
          "refunded";
      }

      next();
    } catch (error) {
      next(error);
    }
  }
);

