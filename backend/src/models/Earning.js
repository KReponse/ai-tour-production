/**
 * Whether money is currently withdrawable.
 */
earningSchema.virtual(
  "isWithdrawable"
).get(function () {
  return (
    this.status === "available" &&
    Number(
      this.availableAmount || 0
    ) > 0
  );
});

/**
 * Backward-compatible alias.
 */
earningSchema.virtual(
  "isAvailable"
).get(function () {
  return (
    this.status === "available"
  );
});

/**
 * Pending earning.
 */
earningSchema.virtual(
  "isProcessing"
).get(function () {
  return (
    this.status === "pending"
  );
});

/**
 * Fully withdrawn.
 */
earningSchema.virtual(
  "isWithdrawn"
).get(function () {
  return (
    this.status === "withdrawn"
  );
});

/**
 * Fully refunded.
 */
earningSchema.virtual(
  "isRefunded"
).get(function () {
  return (
    this.status === "refunded"
  );
});

/**
 * Remaining withdrawable balance.
 */
earningSchema.virtual(
  "remainingWithdrawableAmount"
).get(function () {
  if (
    this.status !== "available"
  ) {
    return 0;
  }

  return roundMoney(
    Math.max(
      0,
      Number(
        this.availableAmount || 0
      )
    )
  );
});

/**
 * MVP platform fee percentage.
 */
earningSchema.virtual(
  "platformFeePercentage"
).get(function () {
  const amount =
    Number(this.amount || 0);

  if (
    amount <= 0
  ) {
    return 0;
  }

  return roundMoney(
    (
      Number(
        this.platformFee || 0
      ) /
      amount
    ) * 100
  );
});

/**
 * Whether the earning has an active reservation.
 */
earningSchema.virtual(
  "hasActiveWithdrawalReservation"
).get(function () {
  return (
    this.withdrawalHistory?.some(
      (allocation) =>
        allocation.status ===
          "reserved" ||
        allocation.status ===
          "processing"
    ) || false
  );
});

// ============================================================
// INTERNAL FINANCIAL VALIDATION
// ============================================================

earningSchema.methods.validateFinancialState =
  function () {
    const amount =
      toNumber(
        this.amount,
        0
      );

    const platformFee =
      toNumber(
        this.platformFee,
        0
      );

    const netAmount =
      toNumber(
        this.netAmount,
        0
      );

    const availableAmount =
      toNumber(
        this.availableAmount,
        0
      );

    const withdrawnAmount =
      toNumber(
        this.withdrawnAmount,
        0
      );

    const refundedAmount =
      toNumber(
        this.refundedAmount,
        0
      );

    if (
      amount <= 0
    ) {
      throw new Error(
        "Earning amount must be greater than 0"
      );
    }

    /*
     * MVP business rule.
     */
    if (
      platformFee !== 0
    ) {
      throw new Error(
        "AI Tour MVP platform fee must be 0"
      );
    }

    if (
      netAmount < 0
    ) {
      throw new Error(
        "Net amount cannot be negative"
      );
    }

    if (
      availableAmount < 0
    ) {
      throw new Error(
        "Available amount cannot be negative"
      );
    }

    if (
      withdrawnAmount < 0
    ) {
      throw new Error(
        "Withdrawn amount cannot be negative"
      );
    }

    if (
      refundedAmount < 0
    ) {
      throw new Error(
        "Refunded amount cannot be negative"
      );
    }

    const allocated =
      roundMoney(
        availableAmount +
          withdrawnAmount +
          refundedAmount
      );

    if (
      allocated >
      roundMoney(netAmount) +
        0.01
    ) {
      throw new Error(
        "Earning financial allocations exceed net amount"
      );
    }

    return true;
  };

// ============================================================
// SYNC FINANCIAL AMOUNTS
// ============================================================

earningSchema.methods.syncFinancialAmounts =
  function () {
    const amount =
      toNumber(
        this.amount,
        0
      );

    /*
     * MVP:
     *
     * Platform commission = 0%.
     */
    this.platformFee = 0;

    this.netAmount =
      roundMoney(amount);

    const withdrawn =
      Math.max(
        0,
        toNumber(
          this.withdrawnAmount,
          0
        )
      );

    const refunded =
      Math.max(
        0,
        toNumber(
          this.refundedAmount,
          0
        )
      );

    /*
     * Only calculate available from the remaining ledger
     * balance.
     */
    this.availableAmount =
      roundMoney(
        Math.max(
          0,
          this.netAmount -
            withdrawn -
            refunded
        )
      );

    return this;
  };

// ============================================================
// MARK AS AVAILABLE
// ============================================================

earningSchema.methods.markAsAvailable =
  async function () {
    if (
      this.status ===
      "refunded"
    ) {
      throw new Error(
        "Refunded earning cannot become available"
      );
    }

    if (
      this.status ===
      "withdrawn"
    ) {
      throw new Error(
        "Withdrawn earning cannot become available"
      );
    }

    this.status =
      "available";

    const withdrawn =
      toNumber(
        this.withdrawnAmount,
        0
      );

    const refunded =
      toNumber(
        this.refundedAmount,
        0
      );

    this.availableAmount =
      roundMoney(
        Math.max(
          0,
          toNumber(
            this.netAmount,
            0
          ) -
            withdrawn -
            refunded
        )
      );

    await this.save();

    return this;
  };

// ============================================================
// RESERVE FOR WITHDRAWAL
// ============================================================

/**
 * Reserve an exact amount for a withdrawal.
 *
 * IMPORTANT:
 *
 * This is NOT proof that money was sent.
 *
 * It only moves money from:
 *
 * availableAmount
 *
 * to:
 *
 * reserved/withdrawnAmount
 *
 * The withdrawal document remains the source of truth
 * for the payout transaction.
 */
earningSchema.methods.reserveForWithdrawal =
  async function (
    withdrawalId,
    amount,
    transactionReference = null
  ) {
    if (
      this.status !==
      "available"
    ) {
      throw new Error(
        "Only available earnings can be reserved for withdrawal"
      );
    }

    if (!withdrawalId) {
      throw new Error(
        "Withdrawal id is required"
      );
    }

    const requestedAmount =
      roundMoney(amount);

    if (
      requestedAmount <= 0
    ) {
      throw new Error(
        "Withdrawal allocation amount must be greater than 0"
      );
    }

    const available =
      roundMoney(
        this.availableAmount
      );

    if (
      requestedAmount >
      available
    ) {
      throw new Error(
        `Insufficient earning balance. Available: ${available}`
      );
    }

    /*
     * Same withdrawal must never be allocated twice
     * to the same earning.
     */
    const existingAllocation =
      this.withdrawalHistory?.find(
        (entry) =>
          String(
            entry.withdrawal
          ) ===
          String(
            withdrawalId
          ) &&
          entry.status !==
            "released"
      );

    if (
      existingAllocation
    ) {
      return this;
    }

    this.availableAmount =
      roundMoney(
        available -
          requestedAmount
      );

    this.withdrawnAmount =
      roundMoney(
        toNumber(
          this.withdrawnAmount,
          0
        ) +
          requestedAmount
      );

    this.withdrawal =
      withdrawalId;

    this.withdrawalHistory.push({
      withdrawal:
        withdrawalId,

      amount:
        requestedAmount,

      currency:
        this.settlementCurrency ||
        this.currency,

      allocatedAt:
        new Date(),

      transactionReference:
        transactionReference ||
        null,

      status:
        "reserved",

      processedAt:
        null,

      failureReason:
        null,
    });

    /*
     * If no balance remains, the earning is fully reserved.
     *
     * It is not necessary to wait until payout to classify
     * the earning as withdrawn because available balance is zero.
     */
    if (
      this.availableAmount <=
      0
    ) {
      this.availableAmount =
        0;

      this.status =
        "withdrawn";

      this.withdrawnAt =
        this.withdrawnAt ||
        new Date();
    }

    await this.save();

    return this;
  };

// ============================================================
// MARK ALLOCATION PROCESSING
// ============================================================

earningSchema.methods.markWithdrawalAllocationProcessing =
  async function (
    withdrawalId,
    transactionReference = null
  ) {
    if (!withdrawalId) {
      throw new Error(
        "Withdrawal id is required"
      );
    }

    const allocation =
      this.withdrawalHistory?.find(
        (entry) =>
          String(
            entry.withdrawal
          ) ===
          String(
            withdrawalId
          )
      );

    if (!allocation) {
      throw new Error(
        "Withdrawal allocation not found"
      );
    }

    if (
      allocation.status ===
      "paid"
    ) {
      return this;
    }

    if (
      allocation.status ===
        "released" ||
      allocation.status ===
        "failed"
    ) {
      throw new Error(
        `Withdrawal allocation cannot enter processing from ${allocation.status}`
      );
    }

    allocation.status =
      "processing";

    if (
      transactionReference
    ) {
      allocation.transactionReference =
        String(
          transactionReference
        ).trim();
    }

    allocation.processedAt =
      new Date();

    await this.save();

    return this;
  };

// ============================================================
// MARK ALLOCATION PAID
// ============================================================

earningSchema.methods.markWithdrawalAllocationPaid =
  async function (
    withdrawalId,
    transactionReference = null
  ) {
    if (!withdrawalId) {
      throw new Error(
        "Withdrawal id is required"
      );
    }

    const allocation =
      this.withdrawalHistory?.find(
        (entry) =>
          String(
            entry.withdrawal
          ) ===
          String(
            withdrawalId
          )
      );

    if (!allocation) {
      throw new Error(
        "Withdrawal allocation not found"
      );
    }

    /*
     * Idempotency.
     */
    if (
      allocation.status ===
      "paid"
    ) {
      return this;
    }

    if (
      allocation.status ===
        "released" ||
      allocation.status ===
        "failed"
    ) {
      throw new Error(
        `Withdrawal allocation cannot be marked paid from ${allocation.status}`
      );
    }

    allocation.status =
      "paid";

    if (
      transactionReference
    ) {
      allocation.transactionReference =
        String(
          transactionReference
        ).trim();
    }

    allocation.processedAt =
      new Date();

    allocation.failureReason =
      null;

    this.withdrawal =
      withdrawalId;

    /*
     * The reserved amount is already included in
     * withdrawnAmount.
     *
     * Therefore we DO NOT add it again here.
     */
    if (
      this.availableAmount <=
      0
    ) {
      this.availableAmount =
        0;

      this.status =
        "withdrawn";

      this.withdrawnAt =
        this.withdrawnAt ||
        new Date();
    } else {
      this.status =
        "available";
    }

    await this.save();

    return this;
  };

// ============================================================
// RELEASE WITHDRAWAL ALLOCATION
// ============================================================

/**
 * Release an amount reserved for a withdrawal.
 *
 * Used when:
 *
 * - withdrawal rejected
 * - payout failed before money was sent
 * - reservation rollback occurred
 *
 * IMPORTANT:
 *
 * This does NOT refund the traveler.
 * It only restores provider's earning balance.
 */
earningSchema.methods.releaseWithdrawalAllocation =
  async function (
    withdrawalId,
    reason = null
  ) {
    if (!withdrawalId) {
      throw new Error(
        "Withdrawal id is required"
      );
    }

    const allocation =
      this.withdrawalHistory?.find(
        (entry) =>
          String(
            entry.withdrawal
          ) ===
          String(
            withdrawalId
          )
      );

    if (!allocation) {
      throw new Error(
        "Withdrawal allocation not found"
      );
    }

    /*
     * Paid money cannot simply be returned to available
     * balance through this method.
     */
    if (
      allocation.status ===
      "paid"
    ) {
      throw new Error(
        "A paid withdrawal allocation cannot be released"
      );
    }

    /*
     * Idempotency.
     */
    if (
      allocation.status ===
      "released"
    ) {
      return this;
    }

    const allocationAmount =
      roundMoney(
        allocation.amount
      );

    allocation.status =
      "released";

    allocation.processedAt =
      new Date();

    allocation.failureReason =
      reason
        ? String(reason)
        : null;

    /*
     * Return exact amount to available.
     */
    this.withdrawnAmount =
      roundMoney(
        Math.max(
          0,
          toNumber(
            this.withdrawnAmount,
            0
          ) -
            allocationAmount
        )
      );

    this.availableAmount =
      roundMoney(
        Math.min(
          toNumber(
            this.netAmount,
            0
          ) -
            toNumber(
              this.refundedAmount,
              0
            ),
          toNumber(
            this.availableAmount,
            0
          ) +
            allocationAmount
        )
      );

    /*
     * If the earning was marked withdrawn only because
     * the reservation consumed its available balance,
     * return it to available state after release.
     */
    if (
      this.status ===
      "withdrawn"
    ) {
      this.status =
        "available";

      this.withdrawnAt =
        null;
    }

    if (
      reason
    ) {
      this.metadata.set(
        `withdrawalFailure:${withdrawalId}`,
        String(reason)
      );
    }

    await this.save();

    return this;
  };

// ============================================================
// MARK ALLOCATION FAILED
// ============================================================

earningSchema.methods.markWithdrawalAllocationFailed =
  async function (
    withdrawalId,
    reason = null
  ) {
    if (!withdrawalId) {
      throw new Error(
        "Withdrawal id is required"
      );
    }

    const allocation =
      this.withdrawalHistory?.find(
        (entry) =>
          String(
            entry.withdrawal
          ) ===
          String(
            withdrawalId
          )
      );

    if (!allocation) {
      throw new Error(
        "Withdrawal allocation not found"
      );
    }

    if (
      allocation.status ===
      "paid"
    ) {
      throw new Error(
        "Paid withdrawal allocation cannot be marked failed"
      );
    }

    if (
      allocation.status ===
      "released"
    ) {
      return this;
    }

    allocation.status =
      "failed";

    allocation.failureReason =
      reason
        ? String(reason)
        : "Withdrawal payout failed";

    allocation.processedAt =
      new Date();

    /*
     * A failed payout before money is received must release
     * the provider's earning.
     */
    const allocationAmount =
      roundMoney(
        allocation.amount
      );

    this.withdrawnAmount =
      roundMoney(
        Math.max(
          0,
          toNumber(
            this.withdrawnAmount,
            0
          ) -
            allocationAmount
        )
      );

    this.availableAmount =
      roundMoney(
        Math.min(
          toNumber(
            this.netAmount,
            0
          ) -
            toNumber(
              this.refundedAmount,
              0
            ),
          toNumber(
            this.availableAmount,
            0
          ) +
            allocationAmount
        )
      );

    if (
      this.availableAmount >
      0
    ) {
      this.status =
        "available";

      this.withdrawnAt =
        null;
    }

    if (
      reason
    ) {
      this.metadata.set(
        `withdrawalFailure:${withdrawalId}`,
        String(reason)
      );
    }

    await this.save();

    return this;
  };

