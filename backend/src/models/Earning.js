/**
 * Mark part/all of an earning as refunded.
 *
 * IMPORTANT:
 *
 * This must only be called after the payment/refund service
 * has confirmed the actual refund.
 */
earningSchema.methods.markAsRefunded =
  async function (
    refundAmount = null
  ) {
    if (
      this.status ===
      "withdrawn"
    ) {
      throw new Error(
        "Withdrawn earning cannot be directly refunded"
      );
    }

    const netAmount =
      roundMoney(
        this.netAmount
      );

    const alreadyRefunded =
      roundMoney(
        this.refundedAmount
      );

    const remainingRefundable =
      roundMoney(
        Math.max(
          0,
          netAmount -
            alreadyRefunded
        )
      );

    const requestedRefund =
      refundAmount === null
        ? remainingRefundable
        : roundMoney(
            refundAmount
          );

    if (
      requestedRefund <=
      0
    ) {
      throw new Error(
        "Refund amount must be greater than 0"
      );
    }

    if (
      requestedRefund >
      remainingRefundable
    ) {
      throw new Error(
        `Refund amount exceeds remaining earning balance. Remaining refundable: ${remainingRefundable}`
      );
    }

    /*
     * Do not allow refund to consume money that is currently
     * reserved for a withdrawal.
     */
    const activeReserved =
      this.withdrawalHistory
        ?.filter(
          (entry) =>
            entry.status ===
              "reserved" ||
            entry.status ===
              "processing"
        )
        .reduce(
          (sum, entry) =>
            sum +
            toNumber(
              entry.amount,
              0
            ),
          0
        ) || 0;

    const currentlyAvailable =
      toNumber(
        this.availableAmount,
        0
      );

    const refundableAvailable =
      roundMoney(
        currentlyAvailable
      );

    /*
     * If a refund would consume reserved funds, reject it.
     */
    if (
      requestedRefund >
      refundableAvailable
    ) {
      throw new Error(
        "Refund cannot consume an active withdrawal reservation"
      );
    }

    this.refundedAmount =
      roundMoney(
        alreadyRefunded +
          requestedRefund
      );

    this.availableAmount =
      roundMoney(
        Math.max(
          0,
          currentlyAvailable -
            requestedRefund
        )
      );

    if (
      this.refundedAmount >=
      netAmount
    ) {
      this.status =
        "refunded";

      this.availableAmount =
        0;
    }

    await this.save();

    return this;
  };

